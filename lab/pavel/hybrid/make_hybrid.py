"""Build a Horizon/BC hybrid Kaggle agent (single self-contained main.py).

Rationale (ladder, 2026-09-26..28): Horizon-family agents beat public tape-clones but lose ~90% to reactive (own-route) top
agents; our BC agents (imitating reactive top teams) are the mirror image. Tape-clones replay one of a few deterministic
public openings, so their unit positions over the first day match a small set of reference sequences exactly, while
reactive top teams leave all references by observation step 1-2.

Policy: play Horizon; every step up to SWITCH_MAX compare the opponent's unit positions with the reference openings; the
first step where no reference matches any more, hand the game to the BC agent for the rest of the episode. The BC agent
observes every step while undecided so its history features are complete. If the opponent still matches a reference at
SWITCH_MAX, the BC agent is dropped and Horizon plays the whole game (identical to the Horizon base vs clones).

usage: python make_hybrid.py --horizon .../es7_wm/pkg/main.py --bc .../np_mix4_mg/main.py \
           --refs ../../../../runs/opening_pos_refs.json --switch-max 24 --out .../main.py
"""
import argparse, base64, json, os, zlib

TEMPLATE = r'''"""Kaggriculture hybrid agent: Horizon vs public tape-clones, behavioural-cloning agent vs reactive opponents.
Generated by lab/pavel/hybrid/make_hybrid.py. Horizon: {horizon_name}. BC: {bc_name}. Switch window: steps 1..{switch_max}."""
import base64, zlib

_REFS = {refs!r}
_SWITCH_MAX = {switch_max}
_FIRST = {first!r}          # "H": Horizon first, hand over to BC on divergence; "B": BC first, hand over to Horizon if clone
_DECIDE = {decide}          # BC-first: decision step (clone = still matching a reference at this observation step)
_H_WATCH = {h_watch!r}      # BC-first: call Horizon (outputs discarded) before the decision so its state follows the game
_H_SRC = {h_src!r}
_B_SRC = {b_src!r}


def _load(src, name):
    ns = {{"__name__": name, "__file__": "/nonexistent/" + name + ".py"}}
    exec(compile(zlib.decompress(base64.b85decode(src)).decode(), name + ".py", "exec"), ns)
    return ns["agent"]


_MODS = {{}}
_ST = {{"last": None, "alive": None, "mode": "H", "switch": None, "err": 0}}


def _get(name):
    if name not in _MODS:
        _MODS[name] = _load(_H_SRC if name == "H" else _B_SRC, "hybrid_" + name)
    return _MODS[name]


def _g(o, k, d=None):
    try:
        v = o.get(k, d)
    except AttributeError:
        v = getattr(o, k, d)
    return d if v is None else v


def _opp_pos(obs):
    p = int(_g(obs, "player", 0)); f = _g(obs, "farms")[1 - p]
    return [list(f["farmer"])] + [list(h) for h in (f.get("hands") or [])]


def hybrid_mode():
    return dict(_ST)


def _agent_bc_first(obs, config, step):
    if _ST["mode"] == "?" and 1 <= step <= _DECIDE:
        try:
            pos = _opp_pos(obs)
            _ST["alive"] = [i for i in _ST["alive"] if _REFS[i][step - 1] == pos]
        except Exception:
            _ST["err"] += 1
        if not _ST["alive"]:
            _ST["mode"] = "B"; _ST["switch"] = step
        elif step == _DECIDE:
            _ST["mode"] = "H"; _ST["switch"] = step
    if _ST["mode"] == "H":
        return _get("H")(obs, config)
    if _ST["mode"] == "?" and _H_WATCH:
        try:
            _get("H")(obs, config)
        except Exception:
            _ST["err"] += 1
    return _get("B")(obs, config)


def agent(obs, config=None):
    step = int(_g(obs, "step", 0))
    if _ST["last"] is None or step <= _ST["last"]:
        _ST.update(last=None, alive=list(range(len(_REFS))), mode="H" if _FIRST == "H" else "?", switch=None)
    _ST["last"] = step
    if _FIRST == "B":
        return _agent_bc_first(obs, config, step)
    if _ST["mode"] == "H" and 1 <= step <= _SWITCH_MAX:
        try:
            pos = _opp_pos(obs)
            _ST["alive"] = [i for i in _ST["alive"] if _REFS[i][step - 1] == pos]
            if not _ST["alive"]:
                _ST["mode"] = "B"; _ST["switch"] = step
        except Exception:
            _ST["err"] += 1
    undecided = _ST["mode"] == "H" and step <= _SWITCH_MAX
    if _ST["mode"] == "B" or undecided:
        try:
            b_action = _get("B")(obs, config)
        except Exception:
            _ST["err"] += 1; b_action = None
        if _ST["mode"] == "B" and b_action is not None:
            return b_action
    return _get("H")(obs, config)
'''


def pack(path):
    return base64.b85encode(zlib.compress(open(path, "rb").read(), 9)).decode()


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--horizon", required=True); ap.add_argument("--bc", required=True)
    ap.add_argument("--refs", required=True); ap.add_argument("--switch-max", type=int, default=24); ap.add_argument("--out", required=True)
    ap.add_argument("--first", default="H", choices=["H", "B"]); ap.add_argument("--decide", type=int, default=2)
    ap.add_argument("--h-watch", action="store_true")
    a = ap.parse_args()
    raw = json.load(open(a.refs)); seqs = {}
    for runs in raw.values():
        for s in runs:
            seqs[json.dumps(s[:a.switch_max])] = s[:a.switch_max]
    refs = list(seqs.values())
    src = TEMPLATE.format(horizon_name=os.path.relpath(a.horizon), bc_name=os.path.relpath(a.bc), switch_max=a.switch_max,
                          refs=refs, h_src=pack(a.horizon), b_src=pack(a.bc), first=a.first, decide=a.decide, h_watch=a.h_watch)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write(src)
    print("wrote", a.out, f"{len(src) / 1e6:.1f} MB; {len(refs)} reference openings")


if __name__ == "__main__":
    main()
